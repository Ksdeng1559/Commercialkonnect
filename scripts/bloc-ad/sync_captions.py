"""Shift the caption cues onto the true voice onset and emit the typed copy.

Whisper's word timestamps are approximate: it can stamp the first word of a
segment at 0.00 even when the speech physically starts a couple of hundred
milliseconds later (the assembled master opens with a deliberate lead-in plus
Piper's own leading silence). A karaoke-style caption that leads the voice by
~200 ms reads as broken, so each scene's cues are shifted by the difference
between the measured acoustic onset and the ASR's first word.

Onset is measured on the narration-only master (no music bed) so the music
cannot mask the start of the phrase.

Reads captions.base.json (produced by gen_captions.py) and writes:
  * public/captions/captions.json
  * src/captions.data.ts  (imported by src/captions.tsx)
"""
import array
import json
import os
import wave
from pathlib import Path

REPO = Path(__file__).resolve().parents[2] / "Videos" / "BLOC"
WORK = Path(os.environ.get("BLOC_WORK_DIR", REPO))
VO = WORK / "public/audio/vo_master.wav"
TRANSCRIPT = WORK / "public/audio/transcript/vo_master_transcript.json"
BASE = WORK / "public/captions/captions.base.json"
OUT = WORK / "public/captions/captions.json"
TS_OUT = REPO / "src/captions.data.ts"

# scene id -> (start_frame, duration_frames), mirrored from src/video.tsx
SCENE_FRAMES = {
    1: (0, 120),
    2: (120, 150),
    3: (270, 150),
    4: (420, 180),
    5: (600, 150),
    6: (750, 150),
}
FPS = 30

# A frame is "voice" when its RMS clears this floor. Piper speech peaks near
# 0.30-0.42 in normalized units and the inter-scene gaps sit at zero, so 0.003
# sits an order of magnitude above the noise while staying well under the
# quietest speech. Calibrated with scripts/calib_onset.py.
RMS_FLOOR = 0.003


def read_wav(path: Path):
    """Read a WAV file as normalized mono float samples.

    The downmix walks the sample buffer by item count, not frame count: with
    a stereo file the frame count is half the number of 16-bit items, and
    walking by frames would read only the first half of the file.
    """
    with wave.open(str(path), "rb") as w:
        nch, sr, n = w.getnchannels(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    a = array.array("h")
    a.frombytes(raw)
    if nch > 1:
        a = array.array("h", [sum(a[i:i + nch]) // nch for i in range(0, len(a), nch)])
    return [x / 32768.0 for x in a], sr


def frame_rms(a, sr, hop_s=0.005):
    hop = max(1, int(sr * hop_s))
    out = []
    for i in range(0, len(a) - hop, hop):
        seg = a[i:i + hop]
        s = sum(x * x for x in seg)
        out.append((i / sr, (s / len(seg)) ** 0.5))
    return out


def onset_in(frames, t0, t1):
    """First time the signal rises above the floor and stays up for ~60ms."""
    run_start = None
    for t, rms in frames:
        if t < t0:
            continue
        if t > t1:
            break
        if rms >= RMS_FLOOR:
            if run_start is None:
                run_start = t
            elif t - run_start >= 0.06:
                return run_start
        else:
            run_start = None
    return None


def scene_of(t: float) -> int:
    for sid, (sf, df) in SCENE_FRAMES.items():
        if sf / FPS <= t < (sf + df) / FPS:
            return sid
    return 1


def write_ts(cues: list[dict]) -> None:
    body = json.dumps(cues, indent=1)
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text(
        "// AUTO-GENERATED by scripts/gen_captions.py + scripts/sync_captions.py.\n"
        "// Do not edit by hand: regenerate after any change to the scene narration\n"
        "// in src/video.tsx.\n"
        "export type CaptionWord={word:string;start:number;end:number};\n"
        "export type CaptionCue={start:number;end:number;text:string;scale?:number;words:CaptionWord[]};\n"
        f"export const CAPTIONS:CaptionCue[]={body};\n"
    )
    print("wrote", TS_OUT)


def main() -> int:
    a, sr = read_wav(VO)
    frames = frame_rms(a, sr)
    data = json.loads(TRANSCRIPT.read_text())
    words = data["word_timestamps"]

    offsets: dict[int, float] = {}
    print(f"{'scene':6} {'window':>14} {'asr_first':>10} {'onset':>8} {'offset':>8}")
    for sid, (sf, df) in SCENE_FRAMES.items():
        t0 = sf / FPS
        t1 = (sf + df) / FPS
        inside = [w for w in words if t0 - 0.05 <= w["start"] < t1]
        asr_first = min((w["start"] for w in inside), default=None)
        on = onset_in(frames, t0, t1)
        off = 0.0 if (asr_first is None or on is None) else round(on - asr_first, 3)
        offsets[sid] = off
        print(f"{sid:<6} {t0:6.2f}-{t1:6.2f} {asr_first!s:>10} {on!s:>8} {off!s:>8}")

    caps = json.loads(BASE.read_text())
    for cue in caps["cues"]:
        off = offsets.get(scene_of(cue["start"]), 0.0)
        cue["start"] = round(cue["start"] + off, 3)
        cue["end"] = round(cue["end"] + off, 3)
        for w in cue.get("words", []):
            w["start"] = round(w["start"] + off, 3)
            w["end"] = round(w["end"] + off, 3)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(caps, indent=1))
    print("caption timings shifted ->", OUT)
    print("offsets:", offsets)
    write_ts(caps["cues"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
